#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
REG=docs/registry.md
{
  echo "# Component Registry"
  echo
  echo "GENERATED by scripts/sync-registry.sh — do not hand-edit."
  echo
  echo "## Skills"
  echo "| Name | Description | Path |"
  echo "|------|-------------|------|"
  for f in skills/*/SKILL.md; do
    [ -f "$f" ] || continue
    d=$(dirname "$f")
    name=$(awk '/^name:/{sub(/^name: */,"");print;exit}' "$f")
    desc=$(awk '/^description:/{sub(/^description: */,"");print;exit}' "$f")
    echo "| ${name:-?} | ${desc:-} | $d |"
  done
  echo
  echo "## MCP Servers"
  echo "| Name | Description | Path |"
  echo "|------|-------------|------|"
  for f in mcp-servers/*/pyproject.toml; do
    [ -f "$f" ] || continue
    d=$(dirname "$f")
    name=$(grep '^name = ' "$f" | head -1 | sed 's/name = //;s/"//g')
    desc=$(grep '^description = ' "$f" | head -1 | sed 's/description = //;s/"//g')
    echo "| ${name:-?} | ${desc:-} | $d |"
  done
  echo
  echo "## Loops"
  echo "| Name | Description | Path |"
  echo "|------|-------------|------|"
  for f in loops/*/loop.md; do
    [ -f "$f" ] || continue
    d=$(dirname "$f")
    name=$(awk '/^name:/{sub(/^name: */,"");print;exit}' "$f")
    desc=$(awk '/^description:/{sub(/^description: */,"");print;exit}' "$f")
    echo "| ${name:-?} | ${desc:-} | $d |"
  done
} > "$REG"
echo "Registry written to $REG"
