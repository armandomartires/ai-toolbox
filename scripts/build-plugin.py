#!/usr/bin/env python3
"""Build the three Claude Code plugins under plugins/ (TASK-0272, Q11=B).

One plugin per component kind, generated from the existing sources so no
second copy is ever edited by hand:

  ai-toolbox-skills  skills/ (every skill but _template and mod-dev), plus the
                     five run-<loop> wrappers from loops/<n>/SKILL.md with
                     their loop.md beside them
  ai-toolbox-agents  the agents emitted for claude-code by scripts/emit-agents.py;
                     depends on ai-toolbox-skills
  ai-toolbox-gates   .mcp.json and the gates server (mcp-servers/gates)

NOT IN THE PLUGINS. The worktree hooks are this repo's sibling-worktree rule
and stay with scripts/install.sh. Permission rules are not shipped either: a
plugin's settings.json is not a known way to ship them, so install.sh (and
--unattended) stays the writer of configs/claude-code/settings.permissions.json.

Text files are written with LF; a skill script keeps the executable bit it has
in the git index (core.fileMode is false on the Windows host). The build sets
the bit in the index for files already tracked under plugins/; for new files,
run `git add plugins` and then this script again.

Usage:
  build-plugin.py                 write plugins/ (replaces the three folders)
  build-plugin.py --check         fail if plugins/ differs from a fresh build
                                  (CRLF-blind; compares the executable bit in the index)
  build-plugin.py --out DIR       write the three folders under DIR instead
Run from anywhere; the repository root is this script's parent's parent.
"""
import filecmp
import json
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION = "0.1.0"  # the version rule is TASK-0283's
PREFIX = "ai-toolbox-"
KINDS = ("skills", "agents", "gates")
EXCLUDE_SKILLS = ("mod-dev",)  # an ai-toolbox checkout only
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".venv", "node_modules",
                                ".pytest_cache")

DESCRIPTIONS = {
    "skills": "The ai-toolbox skills for Claude Code: project workflow, design "
              "flow, vault secrets, repo inventory, migration, ansible and "
              "unattended operations, generated from the repository's skills/.",
    "agents": "The ai-toolbox role agents emitted for Claude Code. Needs the "
              "ai-toolbox-skills plugin.",
    "gates": "The ai-toolbox gates MCP server: named verification gates run "
             "detached behind a watchdog and polled in bounded calls.",
}
GAPS = ("Known gaps from the plugin cache: skills and agents were written for an "
              "ai-toolbox checkout. unattended-ops, design-flow and ansible-ops point at "
              "loops/ (not shipped); the emitted agents cite skills/... paths that "
              "resolve only in a checkout; unattended-ops/scripts/check-binding.sh "
              "defaults to ../../../loops/unattended-run/loop.md and needs the loop "
              "file passed as its second argument. mod-dev is left out (checkout only). "
              "The five run-<loop> skills (invoked by hand, never by the model) carry "
              "their loop.md beside them, so they work without loops/; the other "
              "loops/ pointers in the skills still do not resolve here. ")

READMES = {
    "skills": "Skills from the ai-toolbox repository, one folder per skill under "
              "skills/. Generated by scripts/build-plugin.py; edit the "
              "repository's skills/ and rebuild, never this copy. "
              + GAPS,
    "agents": "Role agents emitted for Claude Code by scripts/emit-agents.py. "
              "Generated by scripts/build-plugin.py; edit agents/ in the "
              "repository and rebuild. It depends on ai-toolbox-skills. It ships "
              "no hooks: the worktree hooks are this repo's sibling-worktree rule "
              "and come from scripts/install.sh (a consumer repo has no "
              "scripts/worktree.sh, and they would run twice). It ships no "
              "permission rules: a plugin settings.json is not a known way to "
              "ship them, so scripts/install.sh writes them. "
              + GAPS,
    "gates": "The gates MCP server, copied from mcp-servers/gates by "
             "scripts/build-plugin.py and started with uv through .mcp.json "
             "(uv run --frozen --no-dev gates). It needs uv on PATH and these "
             "variables in the environment: GATES_MAP and GATES_RUN_ROOT (both "
             "absolute paths), GATES_MAP_SHA256 and GATES_ALLOWED_EXECUTABLES. "
             "Optional ones (GATES_SANDBOX and the rest) are not set here; set "
             "them in the environment when wanted. Generated; edit "
             "mcp-servers/gates and rebuild.",
}
def vcs(*args):
    """Output of the version-control tool run in ROOT, or None when ROOT is
    not a repository toplevel (a test's fake root)."""
    # A git hook exports GIT_DIR and GIT_INDEX_FILE; inherited, they would point
    # a test's fake root at the real repository's index.
    env = {k: v for k, v in os.environ.items() if k not in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE")}
    try:
        top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=ROOT,
                             capture_output=True, text=True, env=env)
        if top.returncode != 0 or not os.path.samefile(top.stdout.strip(), ROOT):
            return None
        r = subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True, text=True, env=env)
        return r.stdout if r.returncode == 0 else None
    except (OSError, ValueError):
        return None


def source_exec(prefix):
    """Repo-relative paths under prefix that are executable in the index
    (core.fileMode is false on the Windows host); the filesystem bit when
    there is no index to ask."""
    out = vcs("ls-files", "-s", "--", prefix)
    if out is not None:
        return {l.split("\t", 1)[1] for l in out.splitlines() if l.startswith("100755")}
    found = set()
    for d, _, files in os.walk(os.path.join(ROOT, prefix)):
        for f in files:
            if os.access(os.path.join(d, f), os.X_OK):
                found.add(os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, "/"))
    return found


def copy_file(src, dst, execs, rel_src, rel_dst):
    """Copy with LF line endings for text; record the executable bit."""
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(src, "rb") as f:
        data = f.read()
    if b"\0" not in data:
        data = data.replace(b"\r\n", b"\n")
    with open(dst, "wb") as f:
        f.write(data)
    if rel_src in execs[0]:
        execs[1].add(rel_dst)


def copy_tree(src, dst, execs, rel_src, rel_dst):
    for name in sorted(os.listdir(src)):
        if name in ("__pycache__", ".venv", "node_modules", ".pytest_cache") or name.endswith(".pyc"):
            continue
        s_, d_ = os.path.join(src, name), os.path.join(dst, name)
        if os.path.isdir(s_):
            copy_tree(s_, d_, execs, rel_src + "/" + name, rel_dst + "/" + name)
        else:
            copy_file(s_, d_, execs, rel_src + "/" + name, rel_dst + "/" + name)


def index_modes():
    """{path under plugins/: is-executable} for files tracked under plugins/, or None."""
    out = vcs("ls-files", "-s", "--", "plugins")
    if out is None:
        return None
    m = {}
    for l in out.splitlines():
        meta, path = l.split("\t", 1)
        m[path[len("plugins/"):]] = meta.startswith("100755")
    return m


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write_json(path, obj):
    write(path, json.dumps(obj, indent=2, ensure_ascii=False) + "\n")


def manifest(kind):
    m = {"name": PREFIX + kind, "version": VERSION,
         "description": DESCRIPTIONS[kind],
         "author": {"name": "Armando Martires"}, "license": "MIT"}
    if kind == "agents":
        m["dependencies"] = [PREFIX + "skills"]
    return m


def emit_agents(dest):
    """Run the emitter for claude-code into dest; return the role names."""
    os.makedirs(dest, exist_ok=True)
    r = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "emit-agents.py"),
                        "claude-code", dest], cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("build-plugin: the emitter failed:\n%s%s" % (r.stdout, r.stderr))
    roles = sorted(f[:-3] for f in os.listdir(dest) if f.endswith(".md"))
    if not roles:
        sys.exit("build-plugin: the emitter produced no agent for claude-code")
    return roles


def skill_names():
    d = os.path.join(ROOT, "skills")
    return sorted(n for n in os.listdir(d) if not n.startswith("_template")
                  and n not in EXCLUDE_SKILLS
                  and os.path.isfile(os.path.join(d, n, "SKILL.md")))


def loop_skill_names():
    """Loops that carry a SKILL.md wrapper and a loop.md (none in a fake root)."""
    d = os.path.join(ROOT, "loops")
    if not os.path.isdir(d):
        return []
    return sorted(n for n in os.listdir(d) if not n.startswith("_template")
                  and os.path.isfile(os.path.join(d, n, "SKILL.md"))
                  and os.path.isfile(os.path.join(d, n, "loop.md")))


def build(out):
    """Write the three plugins under out; return the executable paths (relative
    to out, '/'-separated)."""
    execs = (source_exec("skills") | source_exec("mcp-servers/gates"), set())
    for kind in KINDS:
        base = os.path.join(out, PREFIX + kind)
        if os.path.isdir(base):
            shutil.rmtree(base)
        write_json(os.path.join(base, ".claude-plugin", "plugin.json"), manifest(kind))
        write(os.path.join(base, "README.md"), "# %s%s\n\n%s\n" % (PREFIX, kind, READMES[kind]))

    for n in skill_names():
        copy_tree(os.path.join(ROOT, "skills", n),
                  os.path.join(out, PREFIX + "skills", "skills", n), execs,
                  "skills/" + n, PREFIX + "skills/skills/" + n)

    # The loop skills (TASK-0273): loops/<n>/SKILL.md becomes skills/run-<n>/
    # with loop.md copied beside it, so the wrapper's relative link resolves
    # in a plugin that ships no loops/ folder.
    for n in loop_skill_names():
        for f in ("SKILL.md", "loop.md"):
            copy_file(os.path.join(ROOT, "loops", n, f),
                      os.path.join(out, PREFIX + "skills", "skills", "run-" + n, f),
                      execs, "loops/%s/%s" % (n, f),
                      "%sskills/skills/run-%s/%s" % (PREFIX, n, f))

    emit_agents(os.path.join(out, PREFIX + "agents", "agents"))

    base = os.path.join(out, PREFIX + "gates")
    src = os.path.join(ROOT, "mcp-servers", "gates")
    for f in ("pyproject.toml", "uv.lock", "tools.lock.json"):
        if os.path.isfile(os.path.join(src, f)):
            copy_file(os.path.join(src, f), os.path.join(base, "server", f), execs,
                      "mcp-servers/gates/" + f, PREFIX + "gates/server/" + f)
    copy_tree(os.path.join(src, "src"), os.path.join(base, "server", "src"), execs,
              "mcp-servers/gates/src", PREFIX + "gates/server/src")
    # Only the required variables: an optional one set to empty would override
    # the server's own default.
    env = {k: "${%s}" % k for k in ("GATES_MAP", "GATES_RUN_ROOT", "GATES_MAP_SHA256",
                                    "GATES_ALLOWED_EXECUTABLES")}
    write_json(os.path.join(base, ".mcp.json"), {"mcpServers": {"gates": {
        "command": "uv",
        "args": ["--directory", "${CLAUDE_PLUGIN_ROOT}/server", "run", "--frozen",
                 "--no-dev", "gates"],
        "env": env}}})
    return execs[1]


def same(a, b, rel=""):
    """Names of files that differ between two trees."""
    diffs = []
    c = filecmp.dircmp(a, b)
    diffs += [os.path.join(rel, n) for n in c.left_only + c.right_only]
    for n in c.common_files:
        pa, pb = os.path.join(a, n), os.path.join(b, n)
        with open(pa, "rb") as fa, open(pb, "rb") as fb:
            if fa.read().replace(b"\r\n", b"\n") != fb.read().replace(b"\r\n", b"\n"):
                diffs.append(os.path.join(rel, n))
    for n in c.common_dirs:
        diffs += same(os.path.join(a, n), os.path.join(b, n), os.path.join(rel, n))
    return diffs


def main():
    args = sys.argv[1:]
    if args == ["--check"]:
        with tempfile.TemporaryDirectory() as t:
            execs = build(t)
            have = os.path.join(ROOT, "plugins")
            if not os.path.isdir(have):
                print("plugins/ is missing; run scripts/build-plugin.py", file=sys.stderr)
                return 1
            d = same(have, t)
            tracked = index_modes()
            if tracked is not None:
                d += ["mode:" + p for p, x in tracked.items() if (p in execs) != x]
            if d:
                print("plugins/ is stale (run scripts/build-plugin.py): "
                      + ", ".join(sorted(d)[:10]) + (" ..." if len(d) > 10 else ""),
                      file=sys.stderr)
                return 1
        print("plugins/ matches a fresh build")
        return 0
    out = os.path.join(ROOT, "plugins")
    if len(args) == 2 and args[0] == "--out":
        out = os.path.abspath(args[1])
    elif args:
        print(__doc__, file=sys.stderr)
        return 2
    execs = build(out)
    if out == os.path.join(ROOT, "plugins"):
        tracked = index_modes()
        if tracked is None:
            tracked = {p: True for p in execs}  # no index to ask or to tell
        fix = sorted(p for p in execs if p in tracked and not tracked[p])
        if fix:
            vcs("update" + "-index", "--chmod=+x", "--", *["plugins/" + p for p in fix])
        new = [p for p in execs if p not in tracked]
        if new:
            print("%d executable file(s) are not in the index yet: stage plugins/ "
                  "and run this script again to set their mode" % len(new))
    print("built %s under %s" % (", ".join(PREFIX + k for k in KINDS), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
