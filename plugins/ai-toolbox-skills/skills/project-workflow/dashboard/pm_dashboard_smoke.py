def _token_values(asset_dir):
    """Real token values from the light block of 00-tokens.css."""
    path = Path(asset_dir) / "css" / "00-tokens.css"
    values = {}
    if not path.is_file():
        return values
    text = path.read_text(encoding="utf-8")
    # Both the :root shape/type block and the light palette, which together are
    # what a browser would resolve for the default theme.
    for match in re.finditer(r"(--pm-[a-z0-9-]+)\s*:\s*([^;]+);", text):
        values.setdefault(match.group(1), match.group(2).strip())
    return values


def _sources(asset_dir):
    out = []
    js_dir = Path(asset_dir) / "js"
    for path in sorted(js_dir.glob("*.js")):
        out.append({"name": path.name, "code": path.read_text(encoding="utf-8")})
    return out


def syntax_check(asset_dir=ASSET_DIR, node=None):
    """`node --check` every source. Cheap, and catches a parse error precisely."""
    node = node or shutil.which("node")
    if not node:
        return {"available": False, "results": []}
    results = []
    for path in sorted((Path(asset_dir) / "js").glob("*.js")):
        proc = subprocess.run(
            [node, "--check", str(path)], capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=60,
        )
        results.append({
            "file": path.name,
            "ok": proc.returncode == 0,
            "error": (proc.stderr or "").strip()[:500] if proc.returncode else "",
        })
    return {"available": True, "results": results}


def run(payload=None, asset_dir=ASSET_DIR, node=None, timeout=180, root=None):
    """Load every source against `payload` and invoke every view."""
    node = node or shutil.which("node")
    if not node:
        return {
            "available": False,
            "ok": True,
            "reason": "node is not on PATH; the headless render check was skipped, "
                      "which is not evidence the dashboard works.",
        }

    if payload is None:
        import pm_dashboard

        payload = pm_dashboard.build_payload(root)

    driver = (
        "const TAB_IDS = %s;\n" % json.dumps(list(TABS))
        + "const PAYLOAD_TEXT = %s;\n" % json.dumps(
            json.dumps(payload, sort_keys=True, allow_nan=False)
        )
        + "const TOKEN_VALUES = %s;\n" % json.dumps(_token_values(asset_dir))
        + "const SOURCES = %s;\n" % json.dumps(_sources(asset_dir))
        + DOM_SHIM
    )

    with tempfile.TemporaryDirectory() as tmp:
        script = Path(tmp) / "smoke.mjs"
        script.write_text(driver, encoding="utf-8")
        proc = subprocess.run(
            [node, str(script)], capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=timeout,
        )

    if proc.returncode != 0:
        return {
            "available": True, "ok": False,
            "reason": "the headless driver itself failed to run",
            "stderr": (proc.stderr or "").strip()[:4000],
        }

    line = ""
    for candidate in (proc.stdout or "").splitlines():
        if candidate.strip().startswith("{"):
            line = candidate.strip()
    if not line:
        return {
            "available": True, "ok": False,
            "reason": "the driver produced no JSON result",
            "stdout": (proc.stdout or "")[:2000],
            "stderr": (proc.stderr or "")[:2000],
        }

    report = json.loads(line)
    report["available"] = True
    report["ok"] = _verdict(report)
    report["stderr"] = (proc.stderr or "").strip()[:2000]
    return report


def _verdict(report):
    if report.get("fatal"):
        return False
    for key in ("util", "svg", "theme", "app", "views"):
        if not (report.get("modules") or {}).get(key):
            return False
    for tab, info in (report.get("views") or {}).items():
        if not info.get("present") or not info.get("ok"):
            return False
        if info.get("idempotent") is False:
            return False
        if info.get("suspectText"):
            return False
    for tab, info in (report.get("empty") or {}).items():
        if not info.get("ok"):
            return False
    for issue in report.get("issues") or []:
        if issue.get("kind") in ("load-error", "poison-attribute"):
            return False
    return True


def summarise(report):
    lines = []
    if not report.get("available"):
        lines.append("SKIPPED: " + report.get("reason", "node unavailable"))
        return lines

    if report.get("fatal"):
        lines.append("FATAL: " + report["fatal"])
        return lines
    if report.get("reason"):
        lines.append("FAIL: " + report["reason"])
        for key in ("stderr", "stdout"):
            if report.get(key):
                lines.append("  " + report[key][:1500].replace("\n", "\n  "))
        return lines

    modules = report.get("modules") or {}
    lines.append("modules: " + ", ".join(
        "%s=%s" % (k, "ok" if modules.get(k) else "MISSING")
        for k in ("util", "svg", "theme", "app", "views")
    ))
    lines.append("view functions registered: %d (%s)" % (
        len(report.get("viewNames") or []), ", ".join(report.get("viewNames") or [])
    ))
    lines.append("")
    lines.append("%-10s %-6s %6s %5s %5s %5s %5s %6s %s" % (
        "TAB", "STATE", "NODES", "SVG", "CARD", "TBL", "KPI", "EMPTY", "NOTE"
    ))
    for tab in TABS:
        info = (report.get("views") or {}).get(tab) or {}
        if not info.get("present"):
            lines.append("%-10s %-6s %s" % (tab, "ABSENT", "no view function"))
            continue
        if not info.get("ok"):
            lines.append("%-10s %-6s %s" % (tab, "THREW", info.get("message", "")))
            if info.get("stack"):
                lines.append("           %s" % info["stack"])
            continue
        notes = []
        if info.get("idempotent") is False:
            notes.append("NOT IDEMPOTENT (%s -> %s nodes)"
                         % (info.get("nodes"), info.get("secondNodes")))
        if info.get("suspectText"):
            notes.append("NaN/undefined IN VISIBLE TEXT")
        empty = (report.get("empty") or {}).get(tab) or {}
        if not empty.get("ok"):
            notes.append("crashes on empty payload: %s" % empty.get("message", ""))
        lines.append("%-10s %-6s %6d %5d %5d %5d %5d %6d %s" % (
            tab, "ok", info.get("nodes", 0), info.get("svgs", 0),
            info.get("cards", 0), info.get("tables", 0), info.get("kpis", 0),
            info.get("emptyStates", 0), "; ".join(notes),
        ))

    issues = report.get("issues") or []
    lines.append("")
    if issues:
        lines.append("ISSUES (%d):" % len(issues))
        seen = {}
        for issue in issues:
            key = (issue.get("kind"), issue.get("file") or issue.get("tag"),
                   issue.get("attr"))
            seen.setdefault(key, []).append(issue)
        for key, group in sorted(seen.items(), key=lambda kv: -len(kv[1])):
            first = group[0]
            if first.get("kind") == "load-error":
                lines.append("  [load-error] %s: %s" % (first.get("file"), first.get("message")))
                if first.get("stack"):
                    lines.append("               %s" % first["stack"])
            else:
                lines.append("  [%s] x%d  <%s %s=\"%s\">" % (
                    first.get("kind"), len(group), first.get("tag"),
                    first.get("attr"), first.get("value"),
                ))
    else:
        lines.append("ISSUES: none.")

    created = report.get("created") or {}
    lines.append("")
    lines.append("nodes created in total: %d (%d svg)"
                 % (created.get("total", 0), created.get("svg", 0)))
    lines.append("VERDICT: %s" % ("PASS" if report.get("ok") else "FAIL"))
    return lines


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=(
            "Run the generated dashboard headlessly against a minimal DOM and "
            "report what rendered. Diagnostic: exits 0 even on failure unless "
            "--gate is given."
        )
    )
    ap.add_argument("--json", action="store_true", help="emit the raw report")
    ap.add_argument("--syntax-only", action="store_true",
                    help="only run `node --check` over each source")
    ap.add_argument("--gate", action="store_true",
                    help="exit 1 when the render check fails (a missing node "
                         "still exits 0, and says so)")
    ap.add_argument("--asset-dir", default=str(ASSET_DIR))
    ap.add_argument(
        "--root", default=None,
        help="render against another project's corpus instead of this one. The "
             "generator serves two corpus layouts, and a render check that only "
             "ever sees one of them cannot catch a view that breaks on the "
             "other — which is the whole reason this flag exists.",
    )
    args = ap.parse_args(argv)

    if args.syntax_only:
        result = syntax_check(args.asset_dir)
        if args.json:
            print(json.dumps(result, indent=2))
        elif not result["available"]:
            print("SKIPPED: node is not on PATH.")
        else:
            for entry in result["results"]:
                print("%-20s %s" % (entry["file"], "ok" if entry["ok"] else "PARSE ERROR"))
                if not entry["ok"]:
                    print("  " + entry["error"].replace("\n", "\n  "))
        bad = any(not e["ok"] for e in result["results"])
        return 1 if (args.gate and bad) else 0

    report = run(asset_dir=args.asset_dir, root=args.root)
    if args.json:
        print(json.dumps(report, indent=2, sort_keys=True))
    else:
        print("\n".join(summarise(report)))

    if args.gate and report.get("available") and not report.get("ok"):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
