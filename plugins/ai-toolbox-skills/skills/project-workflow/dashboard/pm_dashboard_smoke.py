"""
pm_dashboard_smoke.py — actually run the generated dashboard, headlessly
(S027.T001_BuildAgileDashboard).

## Why this exists

The dashboard is ~400 KB of hand-written JavaScript rendering twenty SVG charts
from a derived payload. Reading it cannot tell you whether it runs, and three
of its most likely failure modes are *silent*:

1. **A hallucinated API call.** `PM.svg.chart()` has a specific option shape;
   a module that passes `{yDomain: ...}` instead of `{y: {domain: ...}}`
   throws, or worse, quietly scales everything to [0,1].
2. **`NaN` in an SVG attribute.** `d="M NaN,12 L ..."` does not error. The
   browser draws nothing, the card looks deliberately empty, and the number the
   reader wanted is simply absent with no indication anything went wrong. This
   is the single most dangerous bug class in a dashboard, because a blank chart
   reads as "no data" rather than "broken".
3. **A crash on an empty series.** Every array in the payload can be empty on
   some other project, and a view that indexes `[0]` unguarded takes its whole
   tab down there while working perfectly here.

None of that is visible without executing the code. So this module builds a
minimal DOM, loads the real concatenated sources against the real payload,
invokes every registered view, and reports what happened — including a sweep of
every attribute every chart set, looking for `NaN`, `undefined`, `null` and
`Infinity`.

## Why the driver is generated rather than checked in

[[.ai/workflow/decisions/0003-python-only-scripting|ADR-0003]] makes Python the
only scripting language for checked-in automation, and is explicit about the
remedy when a platform tool is needed: "a Python script that shells out via
`subprocess` to the OS-native command, not a native shell script". A checked-in
`.js` harness would be a second scripting language for automation; this module
is Python, and the JavaScript it writes to a temporary file is a generated
artifact, the same way `subprocess` arguments are.

Node is optional. Absent, this reports `available: False` and exits 0 — it is a
diagnostic, and a missing interpreter is not a dashboard defect. Callers that
want a gate read the `ok` field, never the exit code alone.
"""

