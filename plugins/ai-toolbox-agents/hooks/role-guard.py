"""role-guard.py — the Claude Code PreToolUse hook that enforces, per role, the
seven capability terms an agent file cannot express (TASK-0271, ADR-0062;
supersedes ADR-0018 clause 8.3 for those terms).

Shipped by the ai-toolbox-agents plugin as a plugin-level hook (plugin
subagents ignore a `hooks` key in their own frontmatter), matched on Bash,
PowerShell, Monitor, Edit, Write, MultiEdit, NotebookEdit, WebFetch, the tools
in DENIED_TOOLS and every mcp__* tool. It reads the hook input on stdin and
keys on `agent_type`: Claude Code 2.1.321 sends it from inside a subagent and
on the main thread of a `--agent` session. Only `ai-toolbox-agents:<role>`
is guarded; a call from any other agent (a bare name, another plugin's agent,
an agent-team teammate), or from a plain main thread, gets no decision.

The rules come from role-guard.json, generated by
`scripts/emit-agents.py --guard-json=` from agents/<role>/agent.md; never
edit them here. Decisions, in Claude Code's own vocabulary:

  deny  a named forbidden command (no-force-push, no-bypass), a shell tool
        other than Bash for a role whose shell is shaped, an unreadable input,
        a missing role-guard.json for a call from an agent.
  ask   push and WebFetch for the roles that require confirmation; and, until
        `deny_from` in role-guard.json, a call outside the role's allowlist.
  deny  that same out-of-allowlist call from `deny_from` on (Q10=A).
  none  an allowed call: no output, so the normal permission flow, with
        TASK-0276's rules, still decides. The guard never answers `allow`.

An `ask` becomes `deny` when no person answers prompts: any permission mode
other than default, acceptEdits or plan. An input with no permission_mode key
is read as default and keeps the ask (review M3).

It fails closed: anything unexpected while guarding an agent's call is a
deny. It is started by role-guard.sh (review H6), which denies a guarded
agent's call when no working python is found or this script crashes, and
passes every other call on, so a host without python3 loses nothing outside
the guarded roles.

Times are UTC: `--today` defaults to the UTC date, so the switch happens at
00:00 UTC on `deny_from` (review L3).

Test-only flags: --config PATH, --today YYYY-MM-DD (tests/test-role-guard.sh).

No shebang on purpose: it is always run by role-guard.sh as `python3 <path>`
(or `python <path>`), so it needs no executable bit in the index or the plugin.
"""
import datetime
import json
import os
import posixpath
import re
import shlex
import subprocess
import sys

PERSON_MODES = ("default", "acceptEdits", "plan")
# Second risk review H-A: characters whose shell meaning the guard does not
# model (quoting, escapes, expansion, cmd `%x%`). A command holding one is
# outside every allowlist; the deny rules still see its shlex words first.
# Third risk review: ONE parse of the raw text. A character bash and the guard
# could read differently (non-ASCII, NBSP, control characters other than tab
# and newline) is denied outright, as are the expansions the guard does not
# model: `$`, backtick and backslash (so `$'..'`, `${..}`, `$(..)`).
BAD_CHARS = re.compile(r"[^\t\n\x20-\x7e]")
UNMODELLED = re.compile(r"[$`\\]")
GLOBCHARS = re.compile(r"[*?\[]")
PUNCT = "();<>|&\n"
# `@{u}`, `HEAD@{1}`: reflog forms bash does not brace-expand (no `,`, no `..`),
# admitted for read-only git subcommands only.
REFLOG = re.compile(r"^[\w./^~:-]*@\{[\w/:-]*(\.[\w/:-]+)*\}[\w./^~:-]*$")
READONLY_GIT = ("log", "diff", "show", "status", "rev-parse", "reflog", "describe", "shortlog")
# `%` only inside a format value (`--format=%h`, `--pretty=format:%s`).
PCT_OK = re.compile(r"^--(format|pretty|date)=")
# Paths no guarded role may edit, whatever its globs (review M2/H1, H-C, M-C):
# git and hook control, the client's own settings, agents, skills and hooks,
# MCP config, CLAUDE.md, the user's git config; and, from the fourth review's
# MEDIUM, ~/.claude.json (user MCP servers and per-project settings) and the
# rules, output styles and saved workflows a session loads. Matched
# case-insensitively.
PROTECTED = re.compile(r"(^|/)[^/]*\.git(/|$)|(^|/)\.githooks(/|$)|(^|/)\.husky(/|$)"
                       r"|(^|/)\.pre-commit-config\.ya?ml$|(^|/)\.?lefthook(-local)?\.ya?ml$"
                       r"|(^|/)\.claude/(settings[^/]*\.json$|plugins/|agents/|commands/|skills/|hooks/)"
                       r"|(^|/)\.claude/(rules|output-styles|workflows)/|(^|/)\.claude\.json$"
                       r"|(^|/)\.mcp\.json$|(^|/)claude(\.local)?\.md$"
                       r"|(^|/)\.gitconfig$|(^|/)\.config/git/"
                       # Fifth review MEDIUM: the guard's own files and a
                       # plugin's manifest and hooks, and the secret scan's
                       # config the pre-commit hook reads.
                       r"|(^|/)role-guard\.(json|py|sh)$|(^|/)\.claude-plugin/"
                       r"|(^|/)hooks/hooks\.json$|(^|/)\.gitleaks[^/]*$", re.I)
# Windows aliases of a path the protected set would miss (M-C): an 8.3 short
# name segment (`GITHOO~1`) or an NTFS stream suffix (`x::$DATA`, `x:s`).
WIN_ALIAS = re.compile(r"~\d|(?<!^[A-Za-z]):")
# A parent-directory step in a path argument (`bash tests/../../x.sh`), but not
# a git range (`a..b`) (review L6).
PARENT = re.compile(r"(^|[\s/=])\.\.(/|\\|\s|$)")
EDIT_TOOLS = ("Edit", "Write", "MultiEdit", "NotebookEdit")
OTHER_SHELLS = ("PowerShell", "Monitor")
# Tools a guarded role is never offered (review H4, M-D): each can run work,
# reach another agent or project, publish, or leave the worktree outside what
# the guard decides on. Also withheld in the emitted agent file (emit-agents.py
# GUARD_WITHHELD); every MCP tool (`mcp__*`) is denied here, since
# disallowedTools takes no wildcard that the host could verify.
DENIED_TOOLS = ("Workflow", "CronCreate", "CronDelete", "SendMessage", "EnterWorktree",
                "ExitWorktree", "TaskStop", "RemoteTrigger", "SendFile", "ScheduleWakeup",
                "Skill", "SendToProject", "PublishPlugin", "Artifact", "AppifactRepl",
                "request_computer")
# Commands that run their arguments as a command (M-B): unwrapped before the
# deny rules look, so `env git push -f` is a push.
WRAPPERS = ("env", "command", "exec", "nice", "timeout", "xargs", "nohup", "stdbuf",
            "time", "sudo", "doas", "builtin", "ionice", "chrt", "setsid")
SHELL_PROGRAMS = ("sh", "bash", "zsh", "dash", "ksh", "pwsh", "powershell", "cmd", "busybox")
ASSIGN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
# Short git options that REQUIRE a value, so `-m -n` is the message "-n", per
# `git <sub> -h` of git 2.53. Only required values are listed: an option
# missing here makes the guard read its value as options (a false deny, never
# a bypass); one wrongly listed would hide the next word.
GIT_SHORT_VALUE = {"commit": "CFcmtU", "push": "o", "branch": "u", "checkout": "bBU",
                   "switch": "cC"}
# Short git options whose value is OPTIONAL (`-S[<keyid>]`): git takes the rest
# of the cluster as the value and never the next word, so `-Sm -n` is key id
# `m` and then `-n` (fourth review HIGH-2). Per `git <sub> -h` of git 2.53.
GIT_SHORT_OPTVALUE = {"commit": "Su", "branch": "t", "checkout": "t", "switch": "t"}
RANK = {"allow": 1, "ask": 2, "deny": 3}


def out(decision, reason):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": decision,
        "permissionDecisionReason": "role-guard (ADR-0062): " + reason}}))
    return 0


def glob_cmd(pattern, s):
    """OpenCode's command wildcard: `*` is any text, all else literal."""
    rx = "^" + ".*".join(re.escape(p) for p in pattern.split("*")) + "$"
    return re.match(rx, s, re.S) is not None


def glob_path(pattern, rel):
    rx, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            rx, i = rx + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            rx, i = rx + ".*", i + 2
        elif pattern[i] == "*":
            rx, i = rx + "[^/]*", i + 1
        else:
            rx, i = rx + re.escape(pattern[i]), i + 1
    return re.match("^" + rx + "$", rel) is not None


def glob_allow(pattern, s):
    """An allow pattern whose trailing `*` follows a word is anchored: `git
    status*` matches `git status` and `git status -s`, never `git statusX`
    (an alias). Deny patterns stay unanchored, so prefixes still catch."""
    if pattern.startswith("*") and not pattern.startswith("**"):
        # `*run-gate.sh*` (gate-runner, review H2): the EXECUTABLE must be a
        # file of that name, run directly or by bash/sh; the name appearing
        # anywhere else in the command (`python x.py run-gate.sh`) is not it.
        core = pattern.strip("*")
        tokens = s.split()
        if tokens and tokens[0] in ("bash", "sh") and len(tokens) > 1:
            tokens = tokens[1:]
        exe = tokens[0].replace("\\", "/") if tokens else ""
        return exe == core or exe.endswith("/" + core)
    if pattern.endswith("*") and len(pattern) > 1 and pattern[-2].isalnum():
        head = pattern[:-1]
        return glob_cmd(head, s) or glob_cmd(head + " *", s)
    return glob_cmd(pattern, s)


def best(bash, s):
    """The verdict of the longest matching pattern; ties go to the stricter."""
    hits = [(len(p), RANK[a], a) for a in ("allow", "ask", "deny")
            for p in bash.get(a, [])
            if (glob_allow(p, s) if a == "allow" else glob_cmd(p, s))]
    return max(hits)[2] if hits else None


def lex(command):
    """The one token list of a command: shlex (POSIX) with the shell's
    operators as their own tokens and newline as a separator, no comments."""
    lx = shlex.shlex(command, posix=True, punctuation_chars=PUNCT)
    lx.whitespace = " \t"
    lx.whitespace_split = True
    lx.commenters = ""
    return list(lx)


def program(tok):
    base = tok.replace("\\", "/").rsplit("/", 1)[-1].lower()
    return base[:-4] if base.endswith(".exe") else base


def unwrap(toks, depth=0):
    """(the command a token list really runs, why it is unmodelled or None).
    Wrappers are dropped and a shell's `-c` string is lexed as the command; an
    assignment, a wrapper option or any other shell option is unmodelled."""
    t = list(toks)
    if any(x and all(ch in PUNCT for ch in x) for x in t):
        # Reached only for a string a shell or eval parses again (the outer
        # command was refused for any operator already).
        return t, "a shell operator inside a shell or eval string is not admitted"
    while t:
        exe = program(t[0])
        if ASSIGN.match(t[0]):
            return t, "an environment assignment (`%s`) is not modelled" % t[0].split("=")[0]
        if exe in WRAPPERS:
            t = t[1:]
            while t and re.match(r"^[0-9.]+[smhd]?$", t[0]):
                t = t[1:]
            if t and (t[0].startswith("-") or ASSIGN.match(t[0])):
                return t, "the wrapper option or assignment `%s` is not modelled" % t[0]
        elif exe == "!":
            t = t[1:]  # bash's pipeline negation runs the rest (fifth review LOW)
        elif exe == "eval":
            # eval joins its words and parses them again, as `sh -c` does.
            if depth >= 3:
                return t, "nested eval is not modelled"
            try:
                inner = lex(" ".join(t[1:]))
            except ValueError:
                return t, "an eval string that does not parse"
            return unwrap(inner, depth + 1)
        elif exe in SHELL_PROGRAMS:
            for i, a in enumerate(t[1:], 1):
                if a.lower() in ("-c", "/c", "/k", "-command") and depth < 3:
                    try:
                        inner = lex(" ".join(t[i + 1:]))
                    except ValueError:
                        return t, "a shell string that does not parse"
                    return unwrap(inner, depth + 1)
                if a.startswith("-") or (exe == "cmd" and a.startswith("/")):
                    return t, "the shell option `%s` is not modelled" % a
                return t, None  # a script run by the shell
            return t, None
        else:
            return t, None
    return t, None


def git_verdict(gitspec, toks):
    """(a deny reason or None, index of the real end of options). Options are
    parsed as git reads them: short clusters expanded (`-an` = `-a -n`), a
    required short value skipped (`-m --` is a message, not end-of-options),
    a long option denied as a named option or any abbreviation of one."""
    if len(toks) < 2:
        return None, len(toks)
    if toks[1].startswith("-"):
        return "a git option before the subcommand (`%s`)" % toks[1], len(toks)
    sub = toks[1].lower()
    if sub in gitspec.get("subcommands", []):
        return "`git %s` is forbidden for this role" % sub, len(toks)
    table = gitspec.get("options", {})
    names = table.get("*", []) + table.get(sub, [])
    longs = [n[2:] for n in names if n.startswith("--")]
    shorts = [n[1:] for n in names if len(n) == 2 and n[0] == "-"]
    refs = [n for n in names if n in ("+", ":")]
    vals = GIT_SHORT_VALUE.get(sub, "")
    optvals = GIT_SHORT_OPTVALUE.get(sub, "")
    i, end = 2, None
    while i < len(toks):
        t = toks[i]
        if t == "--":
            # Fifth review HIGH-1/2: `--` is NOT always the end of options. A
            # long option taking its value as the next word takes `--` too
            # (`--template -- -an`, `--decorate-refs -- --output=x`), and git
            # reads on as options. Every word after a `--` is still checked
            # as an option or refspec: a pathspec that looks like a denied
            # option is a false deny, never a bypass. Only a `--` that does
            # not directly follow a long option written without `=` is the
            # real end of options, where the glob check (bash expanding a
            # word into an option) stops.
            prev = toks[i - 1]
            if end is None and not (prev.startswith("--") and "=" not in prev and prev != "--"):
                end = i
            i += 1
            continue
        if not t.startswith("-") or t == "-":
            if any(t.startswith(r) for r in refs):
                return "the refspec `%s` forces or deletes" % t, i
        elif t.startswith("--"):
            name = t[2:].split("=", 1)[0].lower()
            hit = next((n for n in longs if name and n.startswith(name)), None)
            if hit:
                return "`--%s` (`--%s`) is forbidden for this role" % (name, hit), i
        else:
            for k, c in enumerate(t[1:], 1):
                if c in shorts:
                    return "`-%s` (in `%s`) is forbidden for this role" % (c, t), i
                if c in optvals:
                    break  # the rest of the cluster is the value; the next word is not
                if c in vals:
                    if k == len(t) - 1:
                        i += 1  # the value is the next token, whatever it is
                    break
        i += 1
    return None, len(toks) if end is None else end


def deny_reason(bash, seg):
    """Why one simple command (a token list) is forbidden, or None."""
    for t in seg:
        if re.match(r"^GIT_[A-Za-z0-9_]*=", t):
            return "a GIT_* assignment (`%s`) redirects git" % t.split("=")[0]
    toks, why = unwrap(seg)
    if why:
        return why
    for text in (" ".join(seg), " ".join(toks)):
        if any(glob_cmd(p, text) for p in bash.get("deny", [])):
            return "`%s` is forbidden for this role" % text
    if toks and program(toks[0]) == "git":
        why, end = git_verdict(bash.get("git") or {}, ["git"] + toks[1:])
        if why:
            return why
        if any(GLOBCHARS.search(t) for t in toks[2:end]):
            return "a glob in a git argument list (bash may expand it to an option)"
    return None


def bash_verdict(bash, command):
    """deny | out | ask | pass, and why. Unmodelled input is a deny; `out`
    (asked in the trial) is kept for a well-formed command outside the
    allowlist."""
    if not isinstance(command, str) or not command.strip():
        return "deny", "a shell call with no command"
    if BAD_CHARS.search(command):
        return "deny", "a non-ASCII or control character bash may read differently"
    if UNMODELLED.search(command):
        return "deny", "`$`, backtick and backslash are not modelled by the guard"
    try:
        toks = lex(command)
    except ValueError:
        return "deny", "unbalanced quoting is not modelled by the guard"
    # Fourth review HIGH-1: shlex joins a run of operator characters into one
    # token (`;(`, `)>|`), which no exact match recognises, so the run was read
    # as an ordinary word and an allow pattern matched past it. Every token
    # made only of operator characters is now a deny, whatever it is: a
    # guarded role runs one simple command per call, with no separator,
    # pipe, redirection, background or group. A quoted operator (`-m ";"`)
    # is denied too, the cost of reading operators one way only.
    ops = [t for t in toks if t and all(ch in PUNCT for ch in t)]
    if ops:
        return "deny", ("the shell operator %r is not admitted for a guarded role: "
                        "one simple command per call" % ops[0])
    segs = [toks] if toks else []
    if not segs:
        return "deny", "a shell call with no command"
    for t in toks:
        if "%" in t and not PCT_OK.match(t):
            return "deny", "`%%` outside a --format value is not modelled (`%s`)" % t
        if ("{" in t or "}" in t) and not (
                REFLOG.match(t) and len(segs) == 1 and len(segs[0]) > 1
                and program(segs[0][0]) == "git" and segs[0][1] in READONLY_GIT):
            return "deny", "brace expansion is not modelled (`%s`)" % t
        if t.startswith("~"):
            return "deny", "tilde expansion is not modelled (`%s`)" % t
    # The one simple command left once every operator is refused above.
    for seg in segs:
        why = deny_reason(bash, seg)
        if why:
            return "deny", why
    verdicts = [(best(bash, " ".join(seg)), seg) for seg in segs]
    for v, seg in verdicts:
        if v == "deny":
            return "deny", "`%s` is forbidden for this role" % " ".join(seg)
    if bash.get("allowlist"):
        seg = segs[0]
        if any(t.startswith("#") for t in seg):
            return "out", "a comment is outside the allowlist"
        if any(re.search(r"\s", t) for t in seg[:2]):
            return "out", "a program or subcommand with a space in it is outside the allowlist"
        if any(t == ".." or t.startswith("../") or "/../" in t or t.endswith("/..")
               or "=../" in t for t in seg):
            return "out", "a `..` path step is outside the allowlist"
        if program(seg[0]) != "git" and any(GLOBCHARS.search(t) for t in seg):
            return "out", "a glob word is outside the allowlist"
        if verdicts[0][0] is None:
            return "out", "`%s` is not in this role's allowlist" % " ".join(seg)
    for v, seg in verdicts:
        if v == "ask":
            return "ask", "`%s` needs a person's confirmation" % " ".join(seg)
    return "pass", ""


def find_git():
    """An absolute git from PATH's absolute entries only: never the current
    directory, which Windows would search first."""
    names = ("git.exe", "git") if os.name == "nt" else ("git",)
    for d in os.environ.get("PATH", "").split(os.pathsep):
        if d and os.path.isabs(d):
            for n in names:
                f = os.path.join(d, n)
                if os.path.isfile(f):
                    return f
    return None


def hooks_dir(cwd):
    """(the repository's hooks directory, lookup failed). `git rev-parse
    --git-path hooks` honours core.hooksPath. Not a repository, or no such
    cwd: (None, False). git missing or erroring: (None, True)."""
    if not cwd or not os.path.isdir(cwd):
        return None, False
    git = find_git()
    if not git:
        return None, True
    try:
        r = subprocess.run([git, "-C", cwd, "rev-parse", "--git-path", "hooks"],
                           capture_output=True, text=True, timeout=3)
    except Exception:
        return None, True
    if r.returncode != 0:
        return None, "not a git repository" not in r.stderr.lower()
    h = r.stdout.strip().replace("\\", "/")
    if not h:
        return None, True
    c = cwd.replace("\\", "/").rstrip("/")
    absolute = h.startswith("/") or re.match(r"^[A-Za-z]:/", h)
    return posixpath.normpath(h if absolute else c + "/" + h), False


def win_segments(p):
    """Each segment without the trailing dots and spaces Windows ignores."""
    return "/".join((seg.rstrip(". ") or seg) for seg in p.split("/"))


def protected(p, cwd):
    """Why the normalized path p may never be edited by a guarded role."""
    q = win_segments(p)
    if PROTECTED.search(q) or PROTECTED.search(p):
        return "a repository, hook or client control file"
    c = (cwd or "").replace("\\", "/").rstrip("/")
    under = bool(c) and q.lower().startswith(c.lower() + "/")
    below = q[len(c):] if under else q
    if WIN_ALIAS.search(below):  # below the cwd, so a short-named cwd still works
        return "an 8.3 short name or an NTFS stream, which can alias a control file"
    hd, failed = hooks_dir(cwd)
    if failed and under:
        return "under a repository whose hooks directory could not be resolved"
    if hd and (q.lower() + "/").startswith(hd.lower().rstrip("/") + "/"):
        return "in the repository's hooks directory"
    return None


def edit_verdict(globs, path, cwd):
    if not isinstance(path, str) or not path:
        return "deny", "an edit with no path"
    p, c = path.replace("\\", "/"), (cwd or "").replace("\\", "/").rstrip("/")
    absolute = p.startswith("/") or re.match(r"^[A-Za-z]:/", p)
    if not absolute:
        p = c + "/" + p
    p = posixpath.normpath(p)
    why = protected(p, cwd)
    if why:
        return "deny", "`%s` is %s" % (path, why)
    if globs is None:
        return "pass", ""
    drive = re.match(r"^[A-Za-z]:/", p)
    under = (p.lower() if drive else p).startswith((c.lower() if drive else c) + "/") if c else False
    if not under:
        return "out", "`%s` is outside the working directory" % path
    rel = p[len(c) + 1:]
    if any(seg.startswith(".") for seg in rel.split("/")):
        # `.github/workflows/x.test.yml` matches `**/*.test.*`; a dot
        # directory is configuration, never a test path (review L6).
        return "out", "`%s` is under a dot directory, not a test path" % rel
    if any(glob_path(g, rel) for g in globs):
        return "pass", ""
    return "out", "`%s` is not a test path" % rel


def decide(cfg, role, data, today):
    spec = cfg["roles"][role]
    tool = data.get("tool_name")
    inp = data.get("tool_input") or {}
    if not isinstance(inp, dict):
        return "deny", "unreadable tool input"
    verdict, why = "pass", ""
    if tool in DENIED_TOOLS or (isinstance(tool, str) and tool.startswith("mcp__")):
        return "deny", "%s is not offered to a guarded role" % tool
    if tool == "Bash" and "bash" in spec:
        verdict, why = bash_verdict(spec["bash"], inp.get("command"))
    elif tool in OTHER_SHELLS and "bash" in spec:
        verdict, why = "deny", "this role's shell allowlist covers Bash only, not %s" % tool
    elif tool in EDIT_TOOLS:
        # Every guarded role: the protected paths; a test-path role: its globs.
        verdict, why = edit_verdict(spec.get("edit"), inp.get("file_path") or inp.get("notebook_path"),
                                    data.get("cwd"))
    elif tool in ("WebFetch", "WebSearch") and spec.get("webfetch") == "ask":
        verdict, why = "ask", "a %s needs a person's confirmation" % (
            "fetch" if tool == "WebFetch" else "web search")
    if verdict == "out":
        if today >= cfg["deny_from"]:
            return "deny", why + " (denied from %s)" % cfg["deny_from"]
        verdict, why = "ask", why + " (asked until %s, denied from then)" % cfg["deny_from"]
    if verdict == "ask" and data.get("permission_mode", "default") not in PERSON_MODES:
        return "deny", why + "; no person answers a prompt in permission mode %s" \
            % data.get("permission_mode")
    return verdict, why


def main(argv):
    here = os.path.dirname(os.path.abspath(__file__))
    cfg_path, today = None, datetime.datetime.now(datetime.timezone.utc).date().isoformat()
    args = list(argv)
    while args:
        a = args.pop(0)
        if a == "--config" and args:
            cfg_path = args.pop(0)
        elif a == "--today" and args:
            today = args.pop(0)
    if cfg_path is None:
        for cand in (os.path.join(here, "role-guard.json"),
                     os.path.join(os.path.dirname(here), "role-guard.json")):
            if os.path.isfile(cand):
                cfg_path = cand
                break
    try:
        data = json.loads(sys.stdin.buffer.read().decode("utf-8"))
        if not isinstance(data, dict):
            raise ValueError("not an object")
    except Exception:
        return out("deny", "the hook input did not parse; failing closed")
    agent = data.get("agent_type")
    if not agent or not isinstance(agent, str):
        return 0
    try:
        with open(cfg_path or os.path.join(here, "role-guard.json"), encoding="utf-8") as fh:
            cfg = json.load(fh)
        # Only the plugin's own agents (`ai-toolbox-agents:<role>`); a bare
        # name is someone else's agent, never ours (review M4).
        if ":" not in agent:
            return 0
        prefix, role = agent.split(":", 1)
        if prefix != cfg.get("plugin"):
            return 0
        if role not in cfg.get("roles", {}):
            return 0
        verdict, why = decide(cfg, role, data, today)
    except Exception as e:  # fail closed for any agent's call
        return out("deny", "the guard could not decide (%s: %s); failing closed"
                   % (type(e).__name__, e))
    if verdict in ("deny", "ask"):
        return out(verdict, why)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
